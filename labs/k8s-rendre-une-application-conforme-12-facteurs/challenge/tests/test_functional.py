"""test_functional.py : k8s-rendre-une-application-conforme-12-facteurs

Ces tests lisent l'état du CLUSTER, jamais les commandes tapées. Le setup pose
dans le namespace douze une application podinfo FAUTIVE : configuration en dur
dans ses arguments, état écrit sur un volume emptyDir du Pod, aucun preStop.
Un Redis tourne à côté, ressource attachée que l'application n'utilise pas.

L'apprenant la rend conforme : configuration générée par Kustomize (nom suffixé
d'un hash), état dans Redis, arrêt propre, graine posée par un Job
d'administration. Rien n'est vrai avant le travail.
"""

from __future__ import annotations

import json
import re
import time
import uuid

import pytest

from conftest import lab_host, lab_target_host, message

NAMESPACE = "douze"
KUBECTL = "sudo kubectl --kubeconfig /etc/kubernetes/admin.conf"
NOM_GENERE = re.compile(r"^podinfo-config-[a-z0-9]{10}$")
VOLUMES_D_ETAT = ("emptyDir", "hostPath")


@pytest.fixture(scope="module")
def host():
    return lab_host(lab_target_host("k8s-cp.lab"))


def _json(host, commande: str) -> dict:
    res = host.run(f"{KUBECTL} -n {NAMESPACE} {commande} -o json")
    assert res.rc == 0, message(
        en=f"`kubectl -n {NAMESPACE} {commande}` failed: {res.stderr.strip()}",
        fr=f"`kubectl -n {NAMESPACE} {commande}` a échoué : {res.stderr.strip()}",
    )
    return json.loads(res.stdout)


def _conteneur(deploy: dict) -> dict:
    conteneurs = deploy["spec"]["template"]["spec"]["containers"]
    return next((c for c in conteneurs if c["name"] == "podinfo"), conteneurs[0])


def _deploiement_pret(host, delai: int = 120) -> dict:
    """Le Deployment podinfo, une fois son rollout terminé."""
    host.run(f"{KUBECTL} -n {NAMESPACE} rollout status deploy/podinfo --timeout={delai}s")
    return _json(host, "get deployment podinfo")


def _url(host, chemin: str) -> str:
    ip = host.run(
        f"{KUBECTL} -n {NAMESPACE} get service podinfo -o jsonpath='{{.spec.clusterIP}}'"
    ).stdout.strip()
    assert ip, message(
        en=f"No Service podinfo in {NAMESPACE}: the application is reached through it.",
        fr=f"Aucun Service podinfo dans {NAMESPACE} : c'est par lui qu'on joint l'application.",
    )
    return f"http://{ip}{chemin}"


# ----------------------------------------------------------------------
# 1. La configuration vient d'un ConfigMap généré par Kustomize.
# ----------------------------------------------------------------------
def test_la_configuration_vient_d_un_configmap_genere(host):
    conteneur = _conteneur(_deploiement_pret(host))
    references = [
        e["configMapRef"]["name"] for e in conteneur.get("envFrom") or [] if "configMapRef" in e
    ]
    generes = [nom for nom in references if NOM_GENERE.match(nom)]
    assert generes, message(
        en=f"The podinfo container takes its configuration from {references or 'no ConfigMap'}. Expected: a "
        "ConfigMap generated by a Kustomize configMapGenerator, whose name ends with a content hash "
        "(podinfo-config-xxxxxxxxxx), injected by envFrom.",
        fr=f"Le conteneur podinfo prend sa configuration dans {references or 'aucun ConfigMap'}. Attendu : un "
        "ConfigMap produit par un configMapGenerator de Kustomize, dont le nom finit par un hash du contenu "
        "(podinfo-config-xxxxxxxxxx), injecté par envFrom.",
    )
    res = host.run(f"{KUBECTL} -n {NAMESPACE} get configmap {generes[0]}")
    assert res.rc == 0, message(
        en=f"The Deployment references {generes[0]}, which does not exist.",
        fr=f"Le Deployment référence {generes[0]}, qui n'existe pas.",
    )
    en_dur = [a for a in (conteneur.get("command") or []) + (conteneur.get("args") or []) if a.startswith("--ui-")]
    assert not en_dur, message(
        en=f"Configuration is still hard-coded in the container arguments: {en_dur}.",
        fr=f"De la configuration reste en dur dans les arguments du conteneur : {en_dur}.",
    )


# ----------------------------------------------------------------------
# 2. L'état vit dans Redis, pas sur le disque du Pod.
# ----------------------------------------------------------------------
def test_l_etat_survit_a_la_suppression_du_pod(host):
    deploy = _deploiement_pret(host)
    volumes = deploy["spec"]["template"]["spec"].get("volumes") or []
    locaux = [v["name"] for v in volumes if any(t in v for t in VOLUMES_D_ETAT)]
    assert not locaux, message(
        en=f"The Pod still carries local state volumes ({', '.join(locaux)}): what is written there dies with "
        "the Pod. The state belongs in the attached Redis.",
        fr=f"Le Pod porte encore des volumes d'état local ({', '.join(locaux)}) : ce qu'on y écrit meurt avec "
        "le Pod. L'état revient au Redis attaché.",
    )
    cle, valeur = f"preuve-{uuid.uuid4().hex[:6]}", uuid.uuid4().hex
    ecrit = host.run(f"curl -s -m 5 -o /dev/null -w '%{{http_code}}' -X POST -d {valeur} {_url(host, '/cache/' + cle)}")
    assert ecrit.stdout.strip() in ("200", "202"), message(
        en=f"Writing to /cache/{cle} answers HTTP {ecrit.stdout.strip() or 'nothing'}: podinfo reaches no cache. "
        "PODINFO_CACHE_SERVER must point to the Redis service.",
        fr=f"L'écriture dans /cache/{cle} répond HTTP {ecrit.stdout.strip() or 'rien'} : podinfo n'atteint aucun "
        "cache. PODINFO_CACHE_SERVER doit viser le service Redis.",
    )
    host.run(f"{KUBECTL} -n {NAMESPACE} delete pod -l app=podinfo --wait=true --timeout=60s")
    fin = time.time() + 90
    relu = ""
    while time.time() < fin:
        res = host.run(f"curl -s -m 5 {_url(host, '/cache/' + cle)}")
        relu = res.stdout.strip()
        if relu == valeur:
            break
        time.sleep(3)
    assert relu == valeur, message(
        en=f"After deleting the Pod, /cache/{cle} gives {relu!r} instead of the written value: the state did not "
        "survive the Pod.",
        fr=f"Après la suppression du Pod, /cache/{cle} rend {relu!r} au lieu de la valeur écrite : l'état n'a pas "
        "survécu au Pod.",
    )


# ----------------------------------------------------------------------
# 3. L'arrêt est propre : un preStop laisse le temps de quitter le Service.
# ----------------------------------------------------------------------
def test_le_conteneur_a_un_prestop(host):
    conteneur = _conteneur(_deploiement_pret(host))
    pre_stop = (conteneur.get("lifecycle") or {}).get("preStop")
    assert pre_stop, message(
        en="The podinfo container has no preStop hook: during a rollout, requests still reach a Pod that is "
        "already shutting down.",
        fr="Le conteneur podinfo n'a pas de crochet preStop : pendant un rollout, des requêtes arrivent encore "
        "sur un Pod qui s'arrête déjà.",
    )


# ----------------------------------------------------------------------
# 4. La graine est posée par un Job d'administration, même image et même config.
# ----------------------------------------------------------------------
def test_la_graine_est_posee_par_le_job_admin_seed(host):
    res = host.run(f"{KUBECTL} -n {NAMESPACE} get job admin-seed -o json")
    assert res.rc == 0, message(
        en="No Job admin-seed in douze: the seed is an administration process, run as a Job.",
        fr="Aucun Job admin-seed dans douze : la graine est un processus d'administration, lancé en Job.",
    )
    job = json.loads(res.stdout)
    termine = any(
        c.get("type") == "Complete" and c.get("status") == "True" for c in job.get("status", {}).get("conditions") or []
    )
    assert termine, message(
        en="The Job admin-seed is not Complete: `kubectl logs job/admin-seed` says why.",
        fr="Le Job admin-seed n'est pas Complete : `kubectl logs job/admin-seed` dit pourquoi.",
    )
    image_job = job["spec"]["template"]["spec"]["containers"][0].get("image", "")
    image_app = _conteneur(_json(host, "get deployment podinfo")).get("image", "")
    assert image_job == image_app, message(
        en=f"The Job runs {image_job}, the application {image_app}: an administration process uses the same "
        "image as the application.",
        fr=f"Le Job tourne en {image_job}, l'application en {image_app} : un processus d'administration utilise "
        "la même image que l'application.",
    )
    graine = host.run(f"curl -s -m 5 {_url(host, '/cache/seed')}").stdout.strip()
    assert graine == "graine-par-le-job", message(
        en=f"/cache/seed gives {graine!r}, not 'graine-par-le-job': the Job did not write the seed into the "
        "application's Redis.",
        fr=f"/cache/seed rend {graine!r}, et non 'graine-par-le-job' : le Job n'a pas écrit la graine dans le "
        "Redis de l'application.",
    )
